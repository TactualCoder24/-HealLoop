"""Aggregate per-subset results into outputs/results.csv + outputs/RESULTS.md (the numbers quoted in the README)."""
from __future__ import annotations

import json

import pandas as pd

from . import mlops
from .config import SUBSETS, load_config, resolve


def collect() -> tuple[pd.DataFrame, dict]:
    rows, extra = [], {}
    for s in SUBSETS:
        cfg = load_config(s)
        try:
            b = mlops.load_champion(cfg)
        except FileNotFoundError:
            continue
        m = b.metrics
        t, v, base = m["test"], m["val"], m["baselines_test"]
        rows.append({
            "subset": s, "model": b.version, "features": b.meta["n_features"], "sensors_kept": len(b.cleaner.kept),
            "test_RMSE": t["rmse"], "test_NASA_score": t["nasa_score"], "test_MAE": t["mae"],
            "test_cov80_vs_capped": t["coverage_80"], "test_interval_width": t["interval_width"],
            "val_RMSE": v["ep_rmse"], "val_cov80": v["ep_coverage_80"],
            "base_const_RMSE": base["constant_median"]["rmse"], "base_age_RMSE": base["age_based"]["rmse"],
            "base_ridge_RMSE": base["ridge_window_features"]["rmse"], "base_ridge_NASA": base["ridge_window_features"]["nasa_score"],
            "alert_A": b.policy.alert_A, "alert_k_of_n": f"{b.policy.alert_k}/{b.policy.alert_n}",
            "cutoffs_crit_high_med": f"{b.policy.crit:g}/{b.policy.high:g}/{b.policy.med:g}", "W_star": round(b.policy.width_star, 1),
            "val_recall_risk_window": m["policy_val_rule_stream"]["recall_risk_window"],
            "val_tickets_per_engine": m["agent_val"]["tickets_per_engine"],
            "val_median_lead_first_P1P2": m["agent_val"]["median_lead_cycles_first_P1P2"],
        })
        od = resolve(cfg, "outputs_dir") / s
        for sc in ("clean", "faults", "retrain"):
            p = od / sc / ("retrain_result.json" if sc == "retrain" else "summary.json")
            if p.exists():
                extra.setdefault(s, {})[sc] = json.loads(p.read_text(encoding="utf-8"))
    return pd.DataFrame(rows), extra


def write_report() -> str:
    df, extra = collect()
    out = resolve(load_config("FD001"), "outputs_dir")
    out.mkdir(parents=True, exist_ok=True)
    if df.empty:
        return "no trained models yet"
    df.to_csv(out / "results.csv", index=False)
    f = lambda x, n=1: f"{x:.{n}f}"
    L = ["# Results (generated by `python -m selfheal report`)", "",
         "All numbers come from the locked official NASA test endpoints (one RUL per test engine) unless stated otherwise. "
         "Cut-offs, W* and the anomaly alert rule are validation-tuned policy settings.", "",
         "## RUL models vs baselines (official test set)", "",
         "| Subset | Test RMSE | NASA score | Ridge RMSE (baseline) | Age RMSE (baseline) | Const RMSE | 80% interval coverage* | width |",
         "|---|---|---|---|---|---|---|---|"]
    for _, r in df.iterrows():
        L.append(f"| {r.subset} | {f(r.test_RMSE, 2)} | {f(r.test_NASA_score, 0)} | {f(r.base_ridge_RMSE, 1)} | {f(r.base_age_RMSE, 1)} | "
                 f"{f(r.base_const_RMSE, 1)} | {f(r.test_cov80_vs_capped, 2)} | {f(r.test_interval_width, 1)} |")
    L += ["", "*coverage of the conformal-calibrated P10-P90 interval against the capped (125) official RUL.", "",
          "## Tuned triage policy and agent behaviour on validation engines (run-to-failure replay)", "",
          "| Subset | A / k-of-n | crit/high/med | W* | recall (RUL<=30) | tickets/engine | median lead of first P1/P2 (cycles) |", "|---|---|---|---|---|---|---|"]
    for _, r in df.iterrows():
        L.append(f"| {r.subset} | {r.alert_A} / {r.alert_k_of_n} | {r.cutoffs_crit_high_med} | {r.W_star} | {f(r.val_recall_risk_window, 3)} | "
                 f"{f(r.val_tickets_per_engine, 2)} | {f(r.val_median_lead_first_P1P2, 1)} |")
    L += ["", "## Closed-loop replay of the official test fleet (clean stream)", "",
          "| Subset | engines | tickets | risk engines (RUL<=30) | flagged P1/P2 ever | P1/P2 at end | healthy (RUL>80) engines | of which P1/P2 at end | drift | data quality |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for s, d in extra.items():
        c = d.get("clean")
        if c:
            L.append(f"| {s} | {c['engines']} | {c['tickets_total']} | {c['risk_engines_rul_le_30']} | {c['risk_engines_flagged_P1P2_ever']} | "
                     f"{c['risk_engines_P1P2_at_end']} | {c['healthy_engines_rul_gt_80']} | {c['healthy_engines_rul_gt_80_with_P1P2_at_end']} | "
                     f"{c['monitor']['drift_status']} | {c['monitor']['quality_status']} |")
    L += ["", "## Fault-injection replay (agent must escalate data problems to a human)", "",
          "| Subset | REVIEW (exception) tickets | drift status | max PSI (sensor) | rejected rows |", "|---|---|---|---|---|"]
    for s, d in extra.items():
        c = d.get("faults")
        if c:
            L.append(f"| {s} | {c['review_tickets']} | {c['monitor']['drift_status']} | {f(c['monitor']['max_psi'], 2)} ({c['monitor']['max_psi_sensor']}) | {c['rejected_rows']} |")
    L += ["", "## Retraining demo (reserved completed run-to-failure histories released -> retrain -> grouped champion/challenger gate)", "",
          "| Subset | released engines | champion -> challenger | held-out NASA(mean) before -> after | held-out RMSE before -> after | official-test RMSE before -> after | official-test NASA before -> after | decision |",
          "|---|---|---|---|---|---|---|---|"]
    for s, d in extra.items():
        c = d.get("retrain")
        if c and not c.get("skipped"):
            L.append(f"| {s} | {c['released']} | v{c['champion_before']} -> v{c['challenger']} | {f(c['champion_val']['hold_ep_nasa_mean'], 2)} -> "
                     f"{f(c['challenger_val']['hold_ep_nasa_mean'], 2)} | {f(c['champion_val']['hold_ep_rmse'], 2)} -> {f(c['challenger_val']['hold_ep_rmse'], 2)} | "
                     f"{f(c['champion_test']['rmse'], 2)} -> {f(c['challenger_test']['rmse'], 2)} | "
                     f"{f(c['champion_test']['nasa_score'], 0)} -> {f(c['challenger_test']['nasa_score'], 0)} | "
                     f"{'PROMOTED -> champion v' + str(c['champion_after']) if c['promoted'] else 'rejected (champion kept)'} |")
    L += ["", "Verified feedback from the released histories (agent works each completed engine to failure, a simulated engineer closes the tickets with ground-truth outcomes):", "",
          "| Subset | confirmed degradation | false alarms | scheduled service | P1/P2 precision | median lead of first P1/P2 (cycles) |", "|---|---|---|---|---|---|"]
    for s, d in extra.items():
        c = d.get("retrain")
        if c and not c.get("skipped"):
            fb = c["feedback"]
            L.append(f"| {s} | {fb['confirmed_degradation']} | {fb['false_alarm']} | {fb['scheduled_service']} | {f(fb['p1p2_precision'] or 0, 2)} | "
                     f"{f(fb['agent_on_completed_histories']['median_lead_cycles_first_P1P2'], 1)} |")
    text = "\n".join(L) + "\n"
    (out / "RESULTS.md").write_text(text, encoding="utf-8")
    return text
